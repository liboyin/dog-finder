#!/usr/bin/env bash
# Daily-refresh launcher for the Sydney dog-finder.
# Invoked by the dog-finder-daily-refresh systemd user service at 13:00
# Australia/Sydney time. The service supplies the 90-minute timeout.
#
# Each run gets a folder runs/<ts>/ holding the deterministic pipeline output,
# Codex's schema-validated verdict response, and the Codex event stream.

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
PYTHON_BIN="${PYTHON_BIN:-python3}"
CODEX_BIN="${CODEX_BIN:-codex}"
PROMPT_FILE="$DIR/prompts/daily-refresh.md"
SCHEMA="$DIR/config/verdicts.schema.json"
LOG="$DIR/logs/daily-refresh.log"
RUNS="$DIR/runs"

export PATH="$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin"
mkdir -p "$RUNS" "$DIR/logs"
cd "$DIR" || { echo "$(date '+%F %T %Z') FATAL: cannot cd to $DIR" >> "$LOG"; exit 1; }

if ! command -v "$PYTHON_BIN" >/dev/null 2>&1; then
  echo "$(date '+%F %T %Z') FATAL: Python interpreter not found: $PYTHON_BIN" >> "$LOG"
  exit 1
fi
if ! command -v "$CODEX_BIN" >/dev/null 2>&1; then
  echo "$(date '+%F %T %Z') FATAL: Codex CLI not found: $CODEX_BIN" >> "$LOG"
  exit 1
fi

# A mkdir on a directory is atomic, so it doubles as a mutex. A lock older than
# four hours is assumed to be left by a crashed run and is retaken.
LOCK="$DIR/.run.lock"
if ! mkdir "$LOCK" 2>/dev/null; then
  LOCK_AGE=$(( $(date +%s) - $(stat -c %Y "$LOCK" 2>/dev/null || echo 0) ))
  if [ "$LOCK_AGE" -gt 14400 ]; then
    echo "$(date '+%F %T %Z') WARN: run lock older than 4h; treating as stale and retaking" >> "$LOG"
    rmdir "$LOCK" 2>/dev/null
    if ! mkdir "$LOCK" 2>/dev/null; then
      echo "$(date '+%F %T %Z') another run holds the lock; skipping" >> "$LOG"
      exit 0
    fi
  else
    echo "$(date '+%F %T %Z') another run holds the lock; skipping" >> "$LOG"
    exit 0
  fi
fi
trap 'rmdir "$LOCK" 2>/dev/null' EXIT

TS="$(date '+%Y%m%d-%H%M%S')"
RUNDIR="$RUNS/$TS"
mkdir -p "$RUNDIR"
STREAM="$RUNDIR/run.stream.jsonl"
REPORT="$RUNDIR/report.txt"
PENDING="$RUNDIR/pending.json"
MANIFEST="$RUNDIR/fetch_manifest.json"
VERDICTS="$RUNDIR/verdicts.json"
STATE="$DIR/data/state.json"
INDEX="$DIR/data/dog-index.md"

echo "===== run started $(date '+%F %T %Z') (ts=$TS) =====" >> "$LOG"

PROMPT="$(awk 'f; /^---$/{f=1}' "$PROMPT_FILE")"
if [ -z "$PROMPT" ]; then
  echo "$(date '+%F %T %Z') FATAL: empty prompt extracted from $PROMPT_FILE" >> "$LOG"
  exit 1
fi

echo "$(date '+%F %T %Z') prune stale state (>90d)" >> "$LOG"
"$PYTHON_BIN" -m src.pipeline prune --state "$STATE" --days 90 >> "$LOG" 2>&1 \
  || echo "$(date '+%F %T %Z') WARN: prune exited non-zero" >> "$LOG"

echo "$(date '+%F %T %Z') collect -> $RUNDIR" >> "$LOG"
"$PYTHON_BIN" -m src.pipeline collect \
  --shelters "$DIR/config/shelters.json" \
  --state "$STATE" \
  --out "$RUNDIR" >> "$LOG" 2>&1 \
  || echo "$(date '+%F %T %Z') WARN: collect exited non-zero; Codex proceeds with whatever artifacts exist" >> "$LOG"

PROMPT="$PROMPT

## This run's artifacts (generated by the launcher)
- pending dogs to judge: $PENDING
- fetch manifest:        $MANIFEST
- Return the schema-valid verdict object for: $VERDICTS
The launcher saves your final response there, merges its verdicts into state, and re-renders the index after you finish."

# The unattended judge needs browser-MCP calls without an interactive approver.
# The CLI's only supported noninteractive option bypasses both approvals and
# sandboxing; the prompt and Playwright's restricted tool inventory therefore
# remain critical safeguards.
echo "$(date '+%F %T %Z') invoking Codex to judge pending dogs; live events in $STREAM" >> "$LOG"
"$CODEX_BIN" exec --dangerously-bypass-approvals-and-sandbox \
  --ephemeral -C "$DIR" --model gpt-5.6-luna \
  --output-schema "$SCHEMA" \
  --output-last-message "$VERDICTS" \
  --json "$PROMPT" </dev/null > "$STREAM" 2>>"$LOG"
if [ $? -ne 0 ]; then
  echo "$(date '+%F %T %Z') FATAL: Codex exited non-zero; see $STREAM" >> "$LOG"
  exit 1
fi

if [ -s "$VERDICTS" ] && "$PYTHON_BIN" "$DIR/src/write_report.py" "$VERDICTS" "$REPORT" "$PENDING" >> "$LOG" 2>&1; then
  :
else
  echo "$(date '+%F %T %Z') FATAL: Codex produced no complete valid verdict response; see $STREAM" >> "$LOG"
  exit 1
fi

echo "$(date '+%F %T %Z') apply verdicts -> $INDEX" >> "$LOG"
"$PYTHON_BIN" -m src.pipeline apply \
  --state "$STATE" \
  --verdicts "$VERDICTS" \
  --index "$INDEX" >> "$LOG" 2>&1
if [ $? -ne 0 ]; then
  echo "$(date '+%F %T %Z') FATAL: apply failed; no Git operations were attempted" >> "$LOG"
  exit 1
fi

if [ -n "$(git status --porcelain -- "$INDEX" "$STATE")" ]; then
  DECISION="$("$PYTHON_BIN" -m src.pipeline index-check --index "$INDEX" 2>>"$LOG")"
  if [ "$DECISION" = "commit" ]; then
    git add "$INDEX" "$STATE"
    if git commit -m "Automated run on $(date '+%F')" -- "$INDEX" "$STATE" >> "$LOG" 2>&1; then
      echo "$(date '+%F %T %Z') committed index/state (dog list changed)" >> "$LOG"
      if git push >> "$LOG" 2>&1; then
        echo "$(date '+%F %T %Z') pushed commit to origin" >> "$LOG"
      else
        echo "$(date '+%F %T %Z') WARN: git push to origin failed" >> "$LOG"
      fi
    else
      echo "$(date '+%F %T %Z') WARN: git commit of index/state failed" >> "$LOG"
    fi
  else
    echo "$(date '+%F %T %Z') index changed but dog list unchanged; keeping changes local" >> "$LOG"
  fi
else
  echo "$(date '+%F %T %Z') no index/state changes" >> "$LOG"
fi

if [ -s "$REPORT" ]; then
  echo "--- report (ts=$TS) ---" >> "$LOG"
  cat "$REPORT" >> "$LOG"
fi

if [ -d "$RUNS" ]; then
  find "$RUNS" -maxdepth 1 -type d -name '[0-9]*-[0-9]*' -mtime +30 -exec rm -rf {} + \
    >> "$LOG" 2>&1 || echo "$(date '+%F %T %Z') WARN: run-artifact retention sweep failed" >> "$LOG"
fi

echo "===== run finished $(date '+%F %T %Z') (exit 0) =====" >> "$LOG"
exit 0
